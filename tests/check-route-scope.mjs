import assert from 'node:assert/strict';
import {excludeStartResults,haversine} from '../dist/geo.js';
import {destinationQueries,extractPlaces} from '../dist/poi.js';
const origin=[10,60],north=metres=>[10,60+metres/6371000*180/Math.PI];
const results=['hotel','fuel','charging','activity'].flatMap(kind=>[2999,3000,3001].map(distance=>({kind,coords:north(distance),distance})));
assert.equal(excludeStartResults(results,origin).length,4);
assert(excludeStartResults(results,origin).every(place=>place.distance===3001));
assert(Math.abs(haversine(origin,north(3000))-3000)<1e-6);
const area={bbox:[10.08,60.08,10.2,60.2],rings:[[[10.08,60.08],[10.2,60.08],[10.2,60.2],[10.08,60.2],[10.08,60.08]]]};
const route=[[10,60],[10.1,60.1]],types=['hotel','fuel','charging','culture'];
const tagSets=[{tourism:'hotel'},{amenity:'fuel'},{amenity:'charging_station'},{tourism:'museum'}];
const elements=tagSets.map((tags,id)=>({type:'node',id,lon:10.18,lat:60.18,tags:{...tags,name:'Mål '+id}}));
elements.push({type:'node',id:99,lon:10.25,lat:60.18,tags:{tourism:'hotel',name:'Utenfor'}});
assert.equal(extractPlaces(elements,route,300,types).length,0);
const matches=extractPlaces(elements,route,300,types,false,area);
assert.equal(matches.length,4);assert(matches.every(place=>place.inDestination&&place.distance>300));
const queries=destinationQueries(area,types);assert(queries.length>1);
for(const query of queries)for(const selector of ['"hotel"','"fuel"','"charging_station"','museum'])assert(query.includes(selector));
assert.deepEqual(destinationQueries(null,types),[]);
console.log('PASS: all categories excluded at and inside 3 km; whole destination includes off-route results without admitting bbox outsiders; destination requests are bounded and include all selected categories.');
