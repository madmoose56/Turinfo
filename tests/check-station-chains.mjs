import assert from 'node:assert/strict';
import {placeChain,chainCounts} from '../dist/hotel-chains.js';
const station=(kind,name,tags={})=>({kind,name,tags});
assert.equal(placeChain(station('fuel','Uno X Jessheim'),'fuel').name,'Uno-X');
assert.equal(placeChain(station('fuel','Circle K sentrum',{brand:'YX'}),'fuel').name,'YX');
assert.equal(placeChain(station('fuel','Lokal stasjon',{brand:'Circle K Norge AS'}),'fuel').name,'Circle K');
assert.equal(placeChain(station('charging','Tesla gammel',{operator:'Kople AS',brand:'Tesla'}),'charging').name,'Kople');
assert.equal(placeChain(station('charging','Lokal',{network:'IONITY'}),'charging').name,'Ionity');
assert.equal(placeChain(station('charging','Recharge sentrum'),'charging').name,'Recharge');
assert.equal(placeChain(station('charging','Meridian parkeringshus'),'charging').id,'other');
assert.equal(placeChain(station('fuel','Ukjent'),'fuel').name,'Øvrige bensinstasjoner');
assert.equal(placeChain(station('charging','Ukjent'),'charging').name,'Øvrige ladestasjoner');
assert.equal(placeChain(station('fuel','YX'),'charging'),null);
assert.equal(placeChain(station('charging','YX'),'fuel'),null);
assert.equal(placeChain(station('charging','Lokal',{operator:'Lokalt ladenett'}),'charging').name,'Lokalt ladenett');
const places=[station('fuel','Circle K A'),station('fuel','B',{brand:'CIRCLE K'}),station('fuel','Uno-X A'),station('fuel','Ukjent'),station('charging','Circle K C')];
assert.deepEqual(chainCounts(places,'fuel'),[{id:null,name:'Alle',count:4},{id:'circle k',name:'Circle K',count:2},{id:'uno-x',name:'Uno-X',count:1},{id:'other',name:'Øvrige bensinstasjoner',count:1}]);
assert.deepEqual(chainCounts([],'charging'),[{id:null,name:'Alle',count:0}]);
console.log('PASS: fuel brands and charging operators canonicalised independently, registered identities take precedence, unknown providers retained, and category-specific counts stay separate.');
